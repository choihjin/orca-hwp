import { download, pins, writeFiles } from './vendor-data.mjs'

const out = new URL('../editor/fonts/', import.meta.url)
const manifest = pins.fonts.files.map(({ file, families, weight, sha256 }) => ({ file, families, weight, sha256 }))
const downloadFiles = entries => Promise.all(entries.map(async ([file, pin]) => [file, await download(pin)]))

const [fonts, licenses] = await Promise.all([
  downloadFiles(pins.fonts.files.map(pin => [pin.file, pin])),
  downloadFiles(Object.entries(pins.fonts.licenses)),
])
const upstream = JSON.parse(Object.fromEntries(licenses)['font-notices.json'])
const upstreamFonts = new Map(upstream.fonts.map(font => [font.file, font]))
const upstreamNotices = new Map(upstream.notices.map(notice => [notice.file, notice.sha256]))
for (const { file, sha256 } of manifest) {
  const entry = upstreamFonts.get(file)
  if (entry?.sha256 !== sha256) throw new Error(`${file}: hash differs from rhwp font-notices.json`)
  for (const license of entry.licenseFiles) {
    if (pins.fonts.licenses[license]?.sha256 !== upstreamNotices.get(license)) {
      throw new Error(`${file}: license differs from rhwp font-notices.json (${license})`)
    }
  }
}

const css = manifest.flatMap(({ file, families, weight }) => families.map(family => `@font-face {
  font-family: ${JSON.stringify(family)};
  src: url("./${file}") format("woff2");
  font-weight: ${weight};
}`)).join('\n\n')

await writeFiles(out, {
  ...Object.fromEntries(fonts),
  'manifest.json': JSON.stringify(manifest, null, 2) + '\n',
  'fonts.css': '/* Generated by build/vendor-fonts.mjs. */\n\n' + css + '\n',
})
await writeFiles(new URL('licenses/', out), Object.fromEntries(licenses))
console.log(`Vendored ${fonts.length} WOFF2 fonts, ${fonts.reduce((sum, [, bytes]) => sum + bytes.length, 0)} B`)
